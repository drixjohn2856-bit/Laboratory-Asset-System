-- ============================================================
-- FUNCTION: GET MY ROLE
-- ============================================================

create or replace function public.get_my_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
    select role
    from public.profiles
    where id = auth.uid();
$$;


-- ============================================================
-- FUNCTION: IS ADMIN
-- ============================================================

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.profiles
        where id = auth.uid()
          and role = 'administrator'
    );
$$;


-- ============================================================
-- FUNCTION: IS STAFF OR ADMIN
-- ============================================================

create or replace function public.is_staff_or_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.profiles
        where id = auth.uid()
          and role in (
              'administrator',
              'laboratory_staff'
          )
    );
$$;


-- ============================================================
-- FUNCTION: SET UPDATED AT
-- ============================================================

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;


-- ============================================================
-- FUNCTION: SET EQUIPMENT AVAILABLE AFTER MAINTENANCE
-- ============================================================

create or replace function public.set_equipment_available_after_maintenance()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin

    if new.maintenance_status = 'Completed'
       and old.maintenance_status is distinct from 'Completed'
    then

        update public.equipment
        set status = 'Available'
        where id = new.equipment_id;

    end if;

    return new;

end;
$$;


-- ============================================================
