-- ============================================================
-- TRIGGER: MAINTENANCE COMPLETED
-- ============================================================

drop trigger if exists maintenance_completed_set_equipment_available
on public.maintenance_requests;

create trigger maintenance_completed_set_equipment_available
after update of maintenance_status
on public.maintenance_requests
for each row
execute function public.set_equipment_available_after_maintenance();

-- Repair equipment linked to maintenance requests completed before the trigger existed.
update public.equipment as e
set status = 'Available'
where exists (
        select 1
        from public.maintenance_requests as m
        where m.equipment_id = e.id
            and m.maintenance_status = 'Completed'
);


-- ============================================================
-- FUNCTION: HANDLE NEW AUTH USER
-- ============================================================

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin

    insert into public.profiles (
        id,
        full_name,
        email
    )
    values (
        new.id,
        coalesce(
            new.raw_user_meta_data ->> 'full_name',
            split_part(new.email, '@', 1)
        ),
        new.email
    );

    return new;

end;
$$;


-- ============================================================
-- TRIGGER: CREATE PROFILE AFTER AUTH SIGNUP
-- ============================================================

-- IMPORTANT:
-- Remove the old trigger first so this SQL can be
-- safely executed multiple times.

drop trigger if exists on_auth_user_created
on auth.users;

create trigger on_auth_user_created
after insert
on auth.users
for each row
execute function public.handle_new_user();


